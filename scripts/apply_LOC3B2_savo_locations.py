def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def already_applied() -> bool:
    return all(
        (PACKAGE / relative).is_file() and
        sha256(PACKAGE / relative) == expected
        for relative, expected in FINAL_HASHES.items()
    )


def verify_input() -> None:
    if not PACKAGE.is_dir():
        raise RuntimeError(f"Package missing: {PACKAGE}")

    for relative, expected in EXPECTED_HASHES.items():
        path = PACKAGE / relative
        if not path.is_file():
            raise RuntimeError(f"Required file missing: {path}")
        actual = sha256(path)
        if actual != expected:
            raise RuntimeError(
                f"Unexpected green LOC-3B1 source for {relative}\n"
                f"expected: {expected}\nactual  : {actual}"
            )

    for relative in NEW_FILES:
        path = PACKAGE / relative
        if path.exists():
            raise RuntimeError(
                f"Unexpected pre-existing LOC-3B2 file: {path}"
            )


def payload_files() -> dict[str, bytes]:
    archive = base64.b64decode("".join(PAYLOAD.split()))
    output: dict[str, bytes] = {}

    with tarfile.open(fileobj=io.BytesIO(archive), mode="r:gz") as bundle:
        for member in bundle.getmembers():
            relative = Path(member.name)
            if (
                member.isdir() or
                relative.is_absolute() or
                ".." in relative.parts or
                member.name not in FINAL_HASHES
            ):
                raise RuntimeError(
                    f"Unsafe or unexpected payload member: {member.name}"
                )
            stream = bundle.extractfile(member)
            if stream is None:
                raise RuntimeError(
                    f"Payload member unreadable: {member.name}"
                )
            output[member.name] = stream.read()

    if set(output) != set(FINAL_HASHES):
        raise RuntimeError("Payload file set does not match final manifest")

    return output


def restore_backup(backup: Path) -> None:
    for relative in NEW_FILES:
        path = PACKAGE / relative
        if path.exists():
            path.unlink()

    with tarfile.open(backup, "r:gz") as archive:
        archive.extractall(PACKAGE.parent.parent)


def main() -> None:
    if already_applied():
        print("LOC-3B2 is already installed and verified.")
        return

    verify_input()

    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    BACKUPS.mkdir(parents=True, exist_ok=True)
    LOGS.mkdir(parents=True, exist_ok=True)

    backup = BACKUPS / f"pre_LOC3B2_savo_locations_{stamp}.tar.gz"
    manifest = LOGS / f"LOC3B2_savo_locations_{stamp}.sha256"

    with tarfile.open(backup, "w:gz") as archive:
        archive.add(
            PACKAGE,
            arcname="core/savo_locations",
        )

    files = payload_files()

    try:
        for relative, content in files.items():
            destination = PACKAGE / relative
            destination.parent.mkdir(parents=True, exist_ok=True)
            staging = destination.with_name(
                destination.name + ".loc3b2.new"
            )
            staging.write_bytes(content)
            staging.chmod(0o644)
            staging.replace(destination)

        for relative, expected in FINAL_HASHES.items():
            path = PACKAGE / relative
            actual = sha256(path)
            if actual != expected:
                raise RuntimeError(
                    f"Final hash mismatch for {relative}\n"
                    f"expected: {expected}\nactual  : {actual}"
                )

        for relative in (
            "test/contracts/test_phase3a_contracts.py",
            "test/contracts/test_phase3b1_contracts.py",
            "test/contracts/test_phase3b2_contracts.py",
        ):
            ast.parse((PACKAGE / relative).read_text(encoding="utf-8"))

        package_xml = (PACKAGE / "package.xml").read_text(encoding="utf-8")
        constants = (
            PACKAGE / "include" / "savo_locations" / "constants.hpp"
        ).read_text(encoding="utf-8")

        if "<version>0.10.0</version>" not in package_xml:
            raise RuntimeError("package.xml version was not updated")

        if '"0.10.0"' not in constants:
            raise RuntimeError("constants.hpp version was not updated")

    except Exception:
        restore_backup(backup)
        raise

    with manifest.open("w", encoding="utf-8") as stream:
        for relative in sorted(FINAL_HASHES):
            path = PACKAGE / relative
            stream.write(f"{sha256(path)}  {path}\n")

    print("LOC-3B2 installed and verified.")
    print(f"Backup : {backup}")
    print(f"Manifest: {manifest}")
    print("Package version: 0.10.0")
    print("Expected CTest targets after build: 22")
    print("Persistent ROS write services: register, approve, set_enabled")
    print("Post-commit LocationEvent publication: enabled")
    print("Fail-closed write readiness: enabled")


if __name__ == "__main__":
    main()
